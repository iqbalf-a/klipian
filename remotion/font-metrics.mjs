// node font-metrics.mjs  ->  src/fontMetrics.ts: the advance width (in em) of every character the channel font has in the Basic Latin and
// Latin-1 ranges, read from public/fonts/Outfit-Bold.ttf (head, cmap format 4, hhea and hmtx). The layout manager (src/layout.ts) uses it to know how
// wide a text is without a browser, so a test, the Studio and a render all place text the same way. Re-run it if the font file changes.
import { readFileSync, writeFileSync } from "node:fs";

const buf = readFileSync(new URL("./public/fonts/Outfit-Bold.ttf", import.meta.url));
const u16 = (o) => buf.readUInt16BE(o), u32 = (o) => buf.readUInt32BE(o);
const tables = {};
for (let i = 0; i < u16(4); i++) { const o = 12 + i * 16; tables[buf.toString("ascii", o, o + 4)] = u32(o + 8); }
const unitsPerEm = u16(tables.head + 18), hmetrics = u16(tables.hhea + 34);
const advance = (gid) => u16(tables.hmtx + 4 * Math.min(gid, hmetrics - 1));
// cmap: find a format 4 subtable (Windows Unicode BMP)
let sub = -1;
for (let i = 0; i < u16(tables.cmap + 2); i++) {
  const o = tables.cmap + 4 + i * 8, off = tables.cmap + u32(o + 4);
  if (u16(off) === 4 && sub < 0) sub = off;
}
if (sub < 0) throw new Error("no format 4 cmap in the font");
const segX2 = u16(sub + 6), ends = sub + 14, starts = ends + segX2 + 2, deltas = starts + segX2, ranges = deltas + segX2;
const glyphOf = (code) => {
  for (let s = 0; s < segX2 / 2; s++) {
    if (code > u16(ends + 2 * s)) continue;
    if (code < u16(starts + 2 * s)) return 0;
    const ro = u16(ranges + 2 * s);
    if (ro === 0) return (code + u16(deltas + 2 * s)) & 0xffff;
    const g = u16(ranges + 2 * s + ro + 2 * (code - u16(starts + 2 * s)));
    return g === 0 ? 0 : (g + u16(deltas + 2 * s)) & 0xffff;
  }
  return 0;
};
const widths = {};
for (let c = 32; c < 0x180; c++) { if (c >= 127 && c < 160) continue; const g = glyphOf(c); if (g) widths[String.fromCharCode(c)] = +(advance(g) / unitsPerEm).toFixed(4); }
for (const c of "→←•–—’‘“”…") { const g = glyphOf(c.charCodeAt(0)); if (g) widths[c] = +(advance(g) / unitsPerEm).toFixed(4); }
const fallback = +(widths.n ?? 0.58).toFixed(3);
writeFileSync(new URL("./src/fontMetrics.ts", import.meta.url), `/* Generated by font-metrics.mjs from public/fonts/Outfit-Bold.ttf: advance widths in em. Do not edit by hand. */
export const FALLBACK_WIDTH = ${fallback};
export const WIDTHS: Record<string, number> = ${JSON.stringify(widths)};
`);
console.log(`${Object.keys(widths).length} characters, em ${unitsPerEm}, n = ${widths.n}, i = ${widths.i}, m = ${widths.m}`);
